#Requires -Version 5.1
<#
.SYNOPSIS
    Emits an SPDX 2.3 SBOM for a StealthPDF release.

.DESCRIPTION
    Package names and versions are read from the project files rather than typed here, so the
    SBOM cannot drift from what actually ships:

      * NuGet packages   - PackageReference entries in StealthPDF.csproj and the TWAIN helper
      * PyMuPDF          - the pin in PdfHelper\fetch-pdfhelper.ps1
      * CPython          - the embeddable version in the same script

    Licence identifiers are declared in the table below, because NuGet packages do not reliably
    carry an SPDX expression in their metadata and a wrong licence is worse than an absent one.
    A package appearing here without a mapping is emitted as NOASSERTION and reported, so a new
    dependency is noticed rather than silently mislabelled.

    Written by hand rather than generated by a scanner on purpose: this is a .NET Framework 4.8
    app whose managed dependencies are woven into the executable by Costura, so there is no
    deps.json for a scanner to read, and its native pieces arrive as embedded resources and a
    portable Python tree. A scanner sees almost none of that.

.PARAMETER Version
    The StealthPDF release version, e.g. 2.0.0.

.PARAMETER OutFile
    Where to write the SPDX JSON document.
#>
param(
    [Parameter(Mandatory)][string]$Version,
    [string]$OutFile = "SBOM.spdx.json"
)

$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot

# SPDX licence identifiers for everything we ship. Keep in step with THIRD-PARTY-NOTICES.txt.
$licenses = @{
    'CommunityToolkit.Mvvm'                      = 'MIT'
    'Costura.Fody'                               = 'MIT'
    'Docnet.Core'                                = 'MIT'
    'Fody'                                       = 'MIT'
    'Microsoft.NETFramework.ReferenceAssemblies' = 'MIT'
    'NTwain'                                     = 'MIT'
    'PDFsharp'                                   = 'MIT'
    'PdfPig'                                     = 'Apache-2.0'
    'PdfSharpCore'                               = 'MIT'
    'PolySharp'                                  = 'MIT'
    'System.Text.Json'                           = 'MIT'
    'Tesseract'                                  = 'Apache-2.0'
}

# Components that are not NuGet packages but are still distributed inside the release.
$extra = @(
    @{ name = 'PyMuPDF'; license = '(AGPL-3.0-only OR LicenseRef-Artifex-Commercial)'
       supplier = 'Artifex Software, Inc.'; url = 'https://github.com/pymupdf/PyMuPDF'
       comment  = 'Shipped as compiled binaries in PdfHelper. Corresponding source accompanies the release as StealthPDF-<version>-thirdparty-src.zip.' }
    @{ name = 'MuPDF'; license = '(AGPL-3.0-only OR LicenseRef-Artifex-Commercial)'
       supplier = 'Artifex Software, Inc.'; url = 'https://mupdf.com'
       comment  = 'Embedded within PyMuPDF; source travels inside the PyMuPDF source distribution.' }
    @{ name = 'CPython'; license = 'PSF-2.0'; supplier = 'Python Software Foundation'
       url = 'https://www.python.org'; comment = 'Windows embeddable distribution shipped in PdfHelper\python.' }
    @{ name = 'PDFium'; license = 'BSD-3-Clause'; supplier = 'The Chromium Authors'
       url = 'https://pdfium.googlesource.com/pdfium/'; comment = 'Native renderer, delivered via Docnet.Core.' }
    @{ name = 'Leptonica'; license = 'BSD-2-Clause'; supplier = 'Leptonica'
       url = 'http://www.leptonica.org'; comment = 'Embedded as a resource and self-extracted for OCR.' }
    @{ name = 'tessdata_best'; license = 'Apache-2.0'; supplier = 'Tesseract OCR'
       url = 'https://github.com/tesseract-ocr/tessdata_best'; comment = 'English and Nepali models bundled; others downloaded on demand.' }
)

# ── Collect NuGet packages from the project files ────────────────────────────
$projects = @(
    (Join-Path $repo 'StealthPDF.csproj'),
    (Join-Path $repo 'TwainHelper\StealthPDF.TwainHelper.csproj')
)
$packages = @{}
foreach ($proj in $projects) {
    if (-not (Test-Path $proj)) { continue }
    foreach ($m in [regex]::Matches((Get-Content $proj -Raw),
        '<PackageReference\s+Include="([^"]+)"\s+Version="([^"]+)"')) {
        $packages[$m.Groups[1].Value] = $m.Groups[2].Value
    }
}
if ($packages.Count -eq 0) { throw "No PackageReference entries found - has the project layout changed?" }

# ── Versions pinned in the PdfHelper build script ────────────────────────────
$fetch = Get-Content (Join-Path $repo 'PdfHelper\fetch-pdfhelper.ps1') -Raw
$pymupdfVer = ([regex]::Match($fetch, "\`$pymupdfVer\s*=\s*'([^']+)'")).Groups[1].Value
$pyVer      = ([regex]::Match($fetch, "\`$pyVer\s*=\s*'([^']+)'")).Groups[1].Value
if (-not $pymupdfVer) { throw "Could not read the PyMuPDF pin from fetch-pdfhelper.ps1" }
if (-not $pyVer)      { throw "Could not read the Python version from fetch-pdfhelper.ps1" }

# ── Build the SPDX document ──────────────────────────────────────────────────
$stamp = (Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')
$spdxPackages = [System.Collections.Generic.List[object]]::new()
$relationships = [System.Collections.Generic.List[object]]::new()
$unmapped = [System.Collections.Generic.List[string]]::new()

$spdxPackages.Add([ordered]@{
    SPDXID           = 'SPDXRef-Package-StealthPDF'
    name             = 'StealthPDF'
    versionInfo      = $Version
    downloadLocation = 'https://github.com/aabhpsy/StealthPDF'
    licenseConcluded = 'GPL-3.0-only'
    licenseDeclared  = 'GPL-3.0-only'
    supplier         = 'Organization: StealthPDF'
    filesAnalyzed    = $false
    copyrightText    = 'NOASSERTION'
})

function Add-Component($id, $name, $version, $license, $supplier, $url, $comment) {
    $pkg = [ordered]@{
        SPDXID           = $id
        name             = $name
        downloadLocation = $(if ($url) { $url } else { 'NOASSERTION' })
        licenseConcluded = $license
        licenseDeclared  = $license
        supplier         = $(if ($supplier) { "Organization: $supplier" } else { 'NOASSERTION' })
        filesAnalyzed    = $false
        copyrightText    = 'NOASSERTION'
    }
    if ($version) { $pkg.versionInfo = $version }
    if ($comment) { $pkg.comment = $comment }
    $script:spdxPackages.Add($pkg)
    $script:relationships.Add([ordered]@{
        spdxElementId      = 'SPDXRef-Package-StealthPDF'
        relationshipType   = 'DEPENDS_ON'
        relatedSpdxElement = $id
    })
}

$i = 0
foreach ($name in ($packages.Keys | Sort-Object)) {
    $i++
    $lic = if ($licenses.ContainsKey($name)) { $licenses[$name] } else { $unmapped.Add($name); 'NOASSERTION' }
    Add-Component "SPDXRef-Package-NuGet-$i" $name $packages[$name] $lic 'NOASSERTION' `
                  "https://www.nuget.org/packages/$name/$($packages[$name])" $null
}

$i = 0
foreach ($c in $extra) {
    $i++
    $ver = switch ($c.name) { 'PyMuPDF' { $pymupdfVer } 'CPython' { $pyVer } default { $null } }
    Add-Component "SPDXRef-Package-Other-$i" $c.name $ver $c.license $c.supplier $c.url $c.comment
}

$doc = [ordered]@{
    spdxVersion       = 'SPDX-2.3'
    dataLicense       = 'CC0-1.0'
    SPDXID            = 'SPDXRef-DOCUMENT'
    name              = "StealthPDF-$Version"
    documentNamespace = "https://stealthpdf.com/spdx/StealthPDF-$Version-$([guid]::NewGuid())"
    creationInfo      = [ordered]@{
        created  = $stamp
        creators = @('Tool: stealthpdf-generate-sbom', 'Organization: StealthPDF')
    }
    packages          = $spdxPackages
    relationships     = $relationships
}

$dir = Split-Path -Parent $OutFile
if ($dir -and -not (Test-Path $dir)) { New-Item -ItemType Directory -Force -Path $dir | Out-Null }
$doc | ConvertTo-Json -Depth 10 | Set-Content -Path $OutFile -Encoding utf8

Write-Host "SBOM written to $OutFile"
Write-Host "  $($packages.Count) NuGet packages, $($extra.Count) other components"
if ($unmapped.Count) {
    Write-Warning "No licence mapping for: $($unmapped -join ', '). Add them to `$licenses in this script and to THIRD-PARTY-NOTICES.txt."
}
